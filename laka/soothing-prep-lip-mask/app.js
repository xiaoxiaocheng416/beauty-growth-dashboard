function renderHeroSummary() {
  const container = document.getElementById("hero-summary");
  const caption = document.getElementById("hero-caption");
  if (caption) {
    caption.textContent = pageData.hero.caption;
  }
  const title = document.createElement("div");
  title.className = "hero-summary-title";
  title.textContent = pageData.hero.summaryTitle;
  container.appendChild(title);
  const grid = document.createElement("div");
  grid.className = "top-grid";
  pageData.hero.cards.forEach((cell) => {
    const article = document.createElement("article");
    article.className = "top-cell";
    article.innerHTML = `
      <strong>${cell.title}</strong>
      ${cell.body ? `<p>${cell.body}</p>` : ""}
      ${cell.bullets ? `<ul>${cell.bullets.map((line) => `<li>${line}</li>`).join("")}</ul>` : ""}
    `;
    grid.appendChild(article);
  });
  container.appendChild(grid);
}

